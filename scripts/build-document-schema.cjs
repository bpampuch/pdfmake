// Generates the runtime structural contract from the shipped declarations.
// Keep this checked-in output reproducible: npm run schema:generate / schema:check.
const ts = require('typescript');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const program = ts.createProgram([path.join(root, 'types/interfaces.d.ts')], { strict: true, module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext, target: ts.ScriptTarget.ES2022, skipLibCheck: false });
const errors = ts.getPreEmitDiagnostics(program);
if (errors.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(errors, { getCanonicalFileName: f => f, getCurrentDirectory: () => root, getNewLine: () => '\n' }));
const checker = program.getTypeChecker();
const source = program.getSourceFile(path.join(root, 'types/interfaces.d.ts'));
const symbol = checker.getSymbolAtLocation(source);
const exportsMap = new Map(checker.getExportsOfModule(symbol).map(s => [s.name, s]));
const nodes = [];
const seen = new Map();
function schema(type) {
  if (seen.has(type.id)) return seen.get(type.id);
  const id = nodes.length; seen.set(type.id, id); nodes.push({});
  const f = type.flags; const F = ts.TypeFlags;
  let node;
  if (f & (F.Any | F.Unknown)) node = { kind: 'unknown' };
  else if (f & F.StringLiteral) node = { kind: 'literal', value: type.value };
  else if (f & F.NumberLiteral) node = { kind: 'literal', value: type.value };
  else if (f & F.BooleanLiteral) node = { kind: 'literal', value: type.intrinsicName === 'true' };
  else if (f & F.String) node = { kind: 'string' };
  else if (f & F.Number) node = { kind: 'number' };
  else if (f & F.Undefined) node = { kind: 'undefined' };
  else if (f & F.Null) node = { kind: 'null' };
  else if (f & F.Never) node = { kind: 'never' };
  else if (type.isUnion()) node = { kind: 'union', items: type.types.map(schema) };
  else if (checker.getSignaturesOfType(type, ts.SignatureKind.Call).length) node = { kind: 'function' };
  else if (checker.isTupleType(type)) node = { kind: 'tuple', items: checker.getTypeArguments(type).map(schema) };
  else if (checker.isArrayType(type)) node = { kind: 'array', item: schema(checker.getTypeArguments(type)[0]) };
  else if (['SVGElement', 'Buffer', 'Date', 'Uint8Array', 'ArrayBuffer'].includes(type.symbol?.name)) node = { kind: 'opaque', name: type.symbol.name };
  else if (type.isIntersection() && type.types.some(t => checker.isArrayType(t))) {
    const array = type.types.find(t => checker.isArrayType(t));
    node = nodes[schema(array)];
  }
  else if (type.isIntersection() && type.types.some(t => t.flags & (F.String | F.Number | F.Boolean | F.StringLiteral | F.NumberLiteral | F.BooleanLiteral))) {
    const primitive = type.types.find(t => t.flags & (F.String | F.Number | F.Boolean | F.StringLiteral | F.NumberLiteral | F.BooleanLiteral));
    node = nodes[schema(primitive)];
  }
  else if (f & F.Object || type.isIntersection()) {
    const properties = {};
    for (const p of checker.getPropertiesOfType(type)) properties[p.name] = { type: schema(checker.getTypeOfSymbolAtLocation(p, p.valueDeclaration || p.declarations?.[0] || source)), optional: !!(p.flags & ts.SymbolFlags.Optional) };
    const index = checker.getIndexTypeOfType(type, ts.IndexKind.String);
    node = { kind: 'object', properties, ...(index ? { index: schema(index) } : {}) };
  } else throw new Error('Unsupported contract: ' + checker.typeToString(type));
  nodes[id] = node;
  return id;
}
const entry = schema(checker.getDeclaredTypeOfSymbol(exportsMap.get('TDocumentDefinitions')));
const output = '// Generated by scripts/build-document-schema.cjs from types/interfaces.d.ts; do not edit.\nexport default ' + JSON.stringify({ entry, nodes }, null, '\t') + ';\n';
const destination = path.join(root, 'src/document-schema.js');
if (process.argv.includes('--check')) { if (fs.readFileSync(destination, 'utf8') !== output) throw new Error('Document schema is stale; run npm run schema:generate'); }
else fs.writeFileSync(destination, output);
console.log(`Document contract: ${nodes.length} schema nodes`);
